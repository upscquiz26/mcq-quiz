def form(title, **extra):
    return {"title": title, "exam_type": "full_length", "source_type": "coaching_test", **extra}


def pdf_files(question_pdf: bytes, answer_pdf: bytes | None = None):
    files = {"pdf_file": ("q.pdf", question_pdf, "application/pdf")}
    if answer_pdf is not None:
        files["answer_file"] = ("a.pdf", answer_pdf, "application/pdf")
    return files


def paper_named(db, title):
    db.rollback()
    return db.query(models.Paper).filter_by(title=title).one()


def questions_of(db, paper):
    db.rollback()
    return {q.question_number: q for q in db.query(models.Question).filter_by(paper_id=paper.id)}


