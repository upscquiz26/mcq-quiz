def test_each_question_gets_a_snapshot_that_stops_before_the_answer(pdf_path):
    from PIL import Image
    (questions, _), images = read(pdf_path, paper_pdf(8))
    assert all(q["source_image"] == f"q{q['question_number']}.jpg" for q in questions)
    q1 = Image.open(os.path.join(images, "q1.jpg"))
    # 7 printed lines (question, 2 statements + wrap, 'Which...', 2 option lines): 6 gaps of 14 pt plus one 10 pt line,
    # padding each side, drawn at 2x. The answer line right below would add another 28 px.
    expected_height = int(((6 * 14 + 10) + 2 * te.SNAPSHOT_PAD) * te.SNAPSHOT_SCALE)
    assert abs(q1.height - expected_height) <= 10, (q1.height, expected_height)
    assert q1.width > 300


def test_a_question_split_across_columns_is_stacked_into_one_snapshot(pdf_path):
    from PIL import Image
    (questions, _), images = read(pdf_path, paper_pdf(20))
    heights = {q["question_number"]: Image.open(os.path.join(images, q["source_image"])).height for q in questions}
    # Each question is 10 printed lines (7 + answer + 2 of explanation) and a column holds 25; the 7 lines of question and
    # options cross a column break for these:
    crossing = {n for n in range(1, 21) if (10 * (n - 1)) // COLUMN_LINES != (10 * (n - 1) + 6) // COLUMN_LINES}
    assert crossing == {3, 8, 13, 18}
    whole = min(heights.values())
    assert {n for n, h in heights.items() if h > whole + 5} == crossing          # two pieces stacked: a little taller
    assert all(h <= whole + 30 for h in heights.values())


